package Loops;

public class BasicLoops {
    public static void main(String[] args){
        for(int i=1; i<=10;i++){
            System.out.print(i+" ");
        }
        System.out.println();
        /*
        Initialization
        Condition check
        Work
        Increment/Decrement
        */
        int i;
        for(i=1; i<=10;i++){
            System.out.print(i+" ");
        }
        System.out.println();
        System.out.print(i);
    }
}
