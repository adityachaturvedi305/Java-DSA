package Arrays1D;

public class ArrayOfOtherDataTypes {
    public static void main(String[] args){
        char[] arr = new char[8];
        for (int i = 0; i < arr.length; i++){
            System.out.print(arr[i]+" ");
        }
        String[] arr1 = {"Abhinav","Sahil"};
        for (int i = 0; i< arr1.length; i++){
            System.out.print(arr1[i]+" ");
        }
    }
}
